#!/usr/bin/env node

/**
 * Knowledge Instructions Installer
 *
 * Writes auto-retrieve instructions for the GSD agent into project-level
 * KNOWLEDGE.md. This file is loaded automatically by GSD (pi) and injected
 * into the system prompt on every turn.
 *
 * Installation is safe-to-run-multiple-times: uses HTML-comment-based
 * delimiters (`<!-- gsd-qdrant-knowledge:start -->` / `end -->`) so that
 * the Qdrant section can be precisely located, updated, and removed without
 * touching any other content in the file — regardless of what ## headings
 * other tools (GitNexus, etc.) may have inserted.
 *
 * Target file:
 *   - <cwd>/.gsd/KNOWLEDGE.md   (project-level — loaded by GSD/pi)
 */

const { existsSync, readFileSync, writeFileSync, mkdirSync, unlinkSync } = require('fs');
const { join, dirname } = require('path');

const MARKER_START = '<!-- gsd-qdrant-knowledge:start -->';
const MARKER_END = '<!-- gsd-qdrant-knowledge:end -->';
const VERSION_PREFIX = '# GSD-QDRANT-TEMPLATE-VERSION: ';

const SECTION_CONTENT = `${VERSION_PREFIX}{{VERSION}}
GSD-Qdrant is installed. Use \`auto_retrieve\` (via \`gsd-qdrant\` MCP server) to query cross-project knowledge.

### When to use

**Use \`auto_retrieve\` for:**
- Library/framework/component questions, API usage, design patterns
- When local search returns nothing or the topic might exist in other GSD projects

### How to call

\`\`\`
auto_retrieve(task: "your task description", limit: 3, includeContent: false)
\`\`\`

Set \`includeContent: true\` when you need full source text, not just summaries.

### Query tips

Before calling, distill your question into **2-4 keywords** (concrete nouns/verbs, no filler).

1. **Keep exact identifiers** — function/class/library names, file paths as-is
2. **Strip conversational framing** — remove questions, polite words, fillers
3. **Include all topics** — list distinct concepts, drop connecting words
4. **Any language works** — bge-m3 is multilingual; keep terms in their original language

### Example

| Natural language question | Keywords |
|---|---|
| "How do I handle JWT authentication in GSD MCP servers?" | \`JWT authentication GSD MCP servers\` |
| "Show me middleware patterns for error handling" | \`middleware patterns error handling\` |
| "Come si usa auto_retrieve per cercare nella knowledge?" | \`auto_retrieve knowledge\` |
| "Best practices for GSD slice planning and task completion" | \`GSD slice planning task completion best practices\` |

### Notes

- Results ranked by semantic relevance + cross-project boost
- MCP server configured in \`.mcp.json\` as \`gsd-qdrant\`
`;

/**
 * Resolve target file path for knowledge instructions.
 *
 * Target:
 *   - <cwd>/.gsd/KNOWLEDGE.md   (project-level — loaded by GSD/pi)
 *
 * @param {string} cwd - Current working directory (project root)
 * @returns {{ knowledgePath: string }}
 */
function resolveKnowledgePaths(cwd) {
  return {
    knowledgePath: join(cwd, '.gsd', 'KNOWLEDGE.md'),
  };
}

/**
 * Extract the template version from file content.
 * Looks inside the Qdrant HTML marker block.
 * Returns null if no version marker is found.
 */
function extractVersion(content) {
  const startIdx = content.indexOf(MARKER_START);
  if (startIdx === -1) return null;

  const endIdx = content.indexOf(MARKER_END, startIdx);
  const block = endIdx !== -1
    ? content.substring(startIdx, endIdx)
    : content.substring(startIdx);

  const match = block.match(/# GSD-QDRANT-TEMPLATE-VERSION:\s*(\d+\.\d+\.\d+)/);
  return match ? match[1] : null;
}

/**
 * Replace the entire Qdrant section delimited by HTML comment markers.
 * Only removes content between (and including) the start/end markers.
 *
 * @param {string} content - The full file content
 * @param {string} replacement - The new content to insert (including markers)
 * @returns {string} The updated content
 */
function replaceQdrantBlock(content, replacement) {
  const startIdx = content.indexOf(MARKER_START);
  if (startIdx === -1) return content; // Marker not present — preserve everything

  let endIdx = content.indexOf(MARKER_END, startIdx);
  if (endIdx === -1) {
    // Malformed: start marker found but no end — treat as no-op
    return content;
  }

  endIdx = endIdx + MARKER_END.length;
  return content.substring(0, startIdx) + replacement + content.substring(endIdx);
}

/**
 * Insert content right after the GSD template intro paragraph.
 *
 * The intro is a fixed string that GSD always writes in KNOWLEDGE.md:
 *   "Agents read this before every unit. Add entries when you discover
 *    something worth remembering."
 *
 * Falls back to "before first ##" if the intro text is not found (e.g. custom
 * KNOWLEDGE.md not generated by GSD setup).
 *
 * @param {string} content - The full file content
 * @param {string} sectionToInsert - The section content to insert
 * @returns {string} The updated content
 */
function insertAfterIntro(content, sectionToInsert) {
  const INTRO_END = 'Agents read this before every unit. Add entries when you discover something worth remembering.';

  // Try to find the known GSD intro anchor
  const introIndex = content.indexOf(INTRO_END);
  if (introIndex !== -1) {
    const insertAt = introIndex + INTRO_END.length;
    const before = content.substring(0, insertAt);
    const after = content.substring(insertAt);
    return before + '\n\n' + sectionToInsert.trim() + '\n' + after;
  }

  // Fallback: insert before the first ## heading
  const lines = content.split('\n');
  let insertAt = -1;
  for (let i = 0; i < lines.length; i++) {
    if (/^##\s+\S/.test(lines[i])) {
      insertAt = i;
      break;
    }
  }

  if (insertAt === -1) {
    // No H2 heading found — append at end
    return content + sectionToInsert + '\n';
  }

  // Insert with a blank line separator before and after
  const parts = [
    content.split('\n').slice(0, insertAt).join('\n'),
    '',
    sectionToInsert.trim(),
    '',
    content.split('\n').slice(insertAt).join('\n')
  ];
  return parts.join('\n');
}

/**
 * Write instructions to KNOWLEDGE.md using HTML-comment-based dedup.
 *
 * @param {string} filePath - Path to the target file
 * @param {string} packageVersion - Current package version
 * @param {string} label - Display label for the file (e.g. "KNOWLEDGE.md")
 * @param {{ force?: boolean }} [options]
 * @returns {{ created: boolean, updated: boolean }}
 */
function writeInstructionsToFile(filePath, packageVersion, label, options = {}) {
  // Ensure directory exists
  const dir = dirname(filePath);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }

  let existingContent = '';
  if (existsSync(filePath)) {
    existingContent = readFileSync(filePath, 'utf-8');
  }

  const hasBlock = existingContent.includes(MARKER_START);
  const installedVersion = extractVersion(existingContent);
  const needsUpdate = !hasBlock || installedVersion !== packageVersion || options.force;

  if (!needsUpdate) {
    console.log(`ℹ️  Auto-retrieve instructions already in ${label}`);
    return { created: false, updated: false };
  }

  if (hasBlock && installedVersion !== packageVersion) {
    // Replace the existing Qdrant block with the updated version.
    // The HTML markers ensure only this block is touched.
    const newBlock = MARKER_START + '\n' +
      SECTION_CONTENT.replace('{{VERSION}}', packageVersion) + '\n' +
      MARKER_END + '\n';
    const newContent = replaceQdrantBlock(existingContent, newBlock);
    writeFileSync(filePath, newContent, 'utf-8');
    console.log(`📝 Updated: ${label} (Qdrant section v${installedVersion} → v${packageVersion})`);
    return { created: false, updated: true };
  }

  // New installation: insert after the GSD intro paragraph.
  // The HTML markers delimit the block precisely.
  const sectionBlock = MARKER_START + '\n' +
    SECTION_CONTENT.replace('{{VERSION}}', packageVersion) + '\n' +
    MARKER_END + '\n';
  const trimmed = existingContent.trim();
  const newContent = trimmed
    ? insertAfterIntro(existingContent, sectionBlock)
    : sectionBlock;
  writeFileSync(filePath, newContent, 'utf-8');
  console.log(`📝 Created: ${label} (auto-retrieve instructions)`);
  return { created: true, updated: false };
}

/**
 * Ensure auto-retrieve instructions are present in project-level KNOWLEDGE.md.
 *
 * @param {{ cwd?: string, force?: boolean }} [options]
 * @param {{ cwd?: string }} [options.cwd] - Project root directory (defaults to process.cwd())
 * @param {{ force?: boolean }} [options.force] - If true, always update even if versions match
 * @returns {{ knowledgeCreated: boolean, knowledgeUpdated: boolean }}
 */
function ensureKnowledgeInstructions(options = {}) {
  const cwd = options.cwd || process.cwd();

  // Read current package version from package.json (source of truth)
  let packageVersion;
  try {
    const pkgPath = join(__dirname, '..', 'package.json');
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf-8'));
    packageVersion = pkg.version;
  } catch (_) {
    packageVersion = null;
  }

  const { knowledgePath } = resolveKnowledgePaths(cwd);

  const knowledgeResult = writeInstructionsToFile(knowledgePath, packageVersion, 'KNOWLEDGE.md', options);

  return {
    knowledgeCreated: knowledgeResult.created,
    knowledgeUpdated: knowledgeResult.updated,
  };
}

/**
 * Remove auto-retrieve instructions from a single file.
 * Only removes the Qdrant section between HTML markers, preserving all other content.
 *
 * @param {string} filePath - Path to the target file
 * @param {string} label - Display label for the file
 * @returns {{ removed: boolean, fileDeleted: boolean }}
 */
function removeInstructionsFromFile(filePath, label) {
  if (!existsSync(filePath)) {
    return { removed: false, fileDeleted: false };
  }

  let content = readFileSync(filePath, 'utf-8');
  const hasBlock = content.includes(MARKER_START);

  if (!hasBlock) {
    return { removed: false, fileDeleted: false };
  }

  // Remove only the content between (and including) the HTML markers.
  const newContent = replaceQdrantBlock(content, '');

  // Clean up: remove leading/trailing blank lines and collapse multiple blank lines
  const trimmed = newContent.replace(/^\n+/, '').replace(/\n+$/, '').replace(/\n{3,}/g, '\n\n');

  if (trimmed) {
    // Section removed but file has other content — write back
    writeFileSync(filePath, trimmed + '\n', 'utf-8');
    console.log(`🧹 Removed Qdrant section from ${label}`);
    return { removed: true, fileDeleted: false };
  } else {
    // File is now empty — delete it
    unlinkSync(filePath);
    console.log(`🧹 Removed Qdrant section from ${label} (file deleted)`);
    return { removed: true, fileDeleted: true };
  }
}

/**
 * Remove auto-retrieve instructions from project-level KNOWLEDGE.md.
 * Only removes the Qdrant section between HTML markers, preserving other content.
 *
 * @param {{ cwd?: string }} [options]
 * @param {{ cwd?: string }} [options.cwd] - Project root directory (defaults to process.cwd())
 * @returns {{ knowledgeRemoved: boolean }}
 */
function removeKnowledgeInstructions(options = {}) {
  const cwd = options.cwd || process.cwd();
  const { knowledgePath } = resolveKnowledgePaths(cwd);

  const knowledgeResult = removeInstructionsFromFile(knowledgePath, 'KNOWLEDGE.md');

  return {
    knowledgeRemoved: knowledgeResult.removed,
  };
}

module.exports = { ensureKnowledgeInstructions, removeKnowledgeInstructions };
